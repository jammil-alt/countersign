-- Access, phase 4 (docs/plan.md §1.26 "Human release"): `access_release` keeps each request for a
-- named person of the client to release a vault item (a connection) to one client agent: who, by
-- which channel, the HMAC of the code (never the code), when it expires, the tries used, and what
-- came of it (released with its window, expired, failed, revoked, or void when a newer request
-- replaced it). A tenant table with RLS forced on app.tenant_ids, like every client table. New
-- table only, so the previous Worker keeps working: it never reads it, and a connection without
-- `config.release` needs no release. Generated by drizzle-kit; the grants, row-level security and
-- trigger at the end are hand-written, as in 0011.
CREATE TABLE "access_release" (
	"id" uuid PRIMARY KEY DEFAULT uuid_generate_v7() NOT NULL,
	"tenant_id" uuid NOT NULL,
	"connection_id" uuid NOT NULL,
	"agent_id" uuid NOT NULL,
	"run_id" uuid NOT NULL,
	"person_id" uuid NOT NULL,
	"channel" text NOT NULL,
	"code_hash" text NOT NULL,
	"expires_at" timestamp with time zone NOT NULL,
	"tries" integer DEFAULT 0 NOT NULL,
	"status" text DEFAULT 'pending' NOT NULL,
	"released_at" timestamp with time zone,
	"valid_until" timestamp with time zone,
	"revoked_by" uuid,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "access_release_id_tenant_key" UNIQUE("id","tenant_id"),
	CONSTRAINT "access_release_status_check" CHECK ("access_release"."status" in ('pending', 'released', 'expired', 'failed', 'revoked', 'void')),
	CONSTRAINT "access_release_channel_check" CHECK ("access_release"."channel" in ('sms', 'email')),
	CONSTRAINT "access_release_tries_check" CHECK ("access_release"."tries" between 0 and 5),
	CONSTRAINT "access_release_released_check" CHECK (("access_release"."status" in ('released', 'revoked')) = ("access_release"."released_at" is not null))
);
