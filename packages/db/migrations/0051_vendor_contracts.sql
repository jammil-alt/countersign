-- Vendor contracts (docs/plan.md §1.104): `vendor_contract`, one row per vendor contract or agreed
-- price sheet a client has (its dates, payment terms, early-pay discount, freight, minimum order,
-- and the signed document it was read from), and `vendor_item.contract_id`, which says a vendor
-- item's list price is that contract's agreed price. A client table with forced row-level
-- security on tenant_id (invariant 1), the Materials pack's; the runtime may read, insert and
-- update it, never delete (a contract ends by its date, and a new one replaces it).
-- Additive only: a new table and a nullable column, so the previous Worker keeps working (it
-- never reads either; a list price it sets stays a plain one). Generated by drizzle-kit from
-- packs/materials/src/schema.ts; the grants, row-level security and the comment are hand-written.
