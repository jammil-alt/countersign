	"website" text,
	"email" text,
	"phone" text,
	"address" jsonb,
	"notes" text,
	"external_refs" jsonb DEFAULT '{}'::jsonb NOT NULL,
	"vendor_id" uuid,
	"source" text DEFAULT 'manual' NOT NULL,
	"created_by" uuid,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "organization_id_tenant_key" UNIQUE("id","tenant_id"),
	CONSTRAINT "organization_vendor_key" UNIQUE("tenant_id","vendor_id"),
