-- The directory (docs/plan.md §1.27): one per client, of the people and organizations its agents
-- work with. `organization` holds the client's organizations (vendor, customer, partner, own, other;
-- several allowed), with `vendor_id` linking a vendor organization to its `vendor` record so there is
-- one entry; `organization_change` logs every change, as `contact_change` does for people. `contact`
-- gains nullable `organization_id`, `title`, `relationship` and `source`, and `external_refs` (ids in
-- connected tools, default `{}`, as the vendor and organization keep them). Tenant tables with RLS
-- forced on app.tenant_ids, like the contact tables. Additive only, so the previous Worker keeps
-- working: it never reads the new tables, and the new contact columns are nullable or default to
-- `{}`, so its inserts still pass. Generated by drizzle-kit; the grants, row-level security and
-- trigger at the end are hand-written, as in 0006 and 0013.
