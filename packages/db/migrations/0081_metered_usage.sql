-- A client's rows in its own scope, the back office's (`ours`) only to operator sessions, and rows
-- with no client (the platform's own: an operator's sign-in code, the dev queue) only to operator
-- sessions too. Any session may write a row with no client, which is always ours: a sign-in code
-- is sent before the person has a client in scope.
CREATE POLICY tenant_isolation ON metered_usage FOR ALL TO PUBLIC
  USING ((tenant_id = any(app_tenant_ids()) AND (NOT ours OR app_is_operator()))
    OR (tenant_id IS NULL AND app_is_operator()))
  WITH CHECK (tenant_id = any(app_tenant_ids()) OR (tenant_id IS NULL AND ours));
