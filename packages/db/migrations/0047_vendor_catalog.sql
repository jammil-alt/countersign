-- The backfill, so the catalog starts full. Every client's rows at once, as the owner (past RLS);
-- each row stays in its own client (every join is on tenant_id). Aliases and prices still on a
-- merged item are left (a merge moves them, so there should be none).
-- 1. A vendor item for each SKU a vendor has used, on the item its latest alias names (a person's
-- alias first). Its name is the vendor's latest wording for that item, else the master item's.
-- DECISION: backfilled vendor items are priced in the master item's standard unit
-- (`vendor_uom` = the standard unit, `std_per_vendor_uom` = 1), since every price kept so far is
-- per standard unit; a pack size is learned from the next invoice or set by a person.
INSERT INTO vendor_item
  (tenant_id, vendor_id, catalog_item_id, sku, name, vendor_uom, std_per_vendor_uom, ext)
SELECT DISTINCT ON (a.tenant_id, a.vendor_id, upper(btrim(a.vendor_sku)))
  a.tenant_id, a.vendor_id, a.catalog_item_id, upper(btrim(a.vendor_sku)),
  coalesce(
    (SELECT d.normalized_description FROM item_alias d
     WHERE d.tenant_id = a.tenant_id AND d.vendor_id = a.vendor_id
       AND d.catalog_item_id = a.catalog_item_id AND d.normalized_description IS NOT NULL
     ORDER BY d.updated_at DESC, d.id DESC LIMIT 1),
    ci.canonical_name),
  ci.standard_uom, 1, '{"backfilled": "0047"}'::jsonb
FROM item_alias a
JOIN catalog_item ci ON ci.id = a.catalog_item_id AND ci.tenant_id = a.tenant_id
WHERE a.vendor_sku IS NOT NULL AND length(btrim(a.vendor_sku)) BETWEEN 1 AND 100
  AND ci.merged_into_id IS NULL
ORDER BY a.tenant_id, a.vendor_id, upper(btrim(a.vendor_sku)), (a.source = 'human') DESC,
  a.updated_at DESC, a.id DESC
