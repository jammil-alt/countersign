-- The vendor catalog (docs/plan.md §1.88): `vendor_item`, one row per item a vendor sells the
-- client (its SKU, wording, pack and unit, its last price), each pointing at exactly one master
-- item (`catalog_item`, vendor-neutral). `item_alias.vendor_item_id` and
-- `price_observation.vendor_item_id` (nullable) say which vendor item a wording or a price was.
-- A client table with forced row-level security on tenant_id (invariant 1), the pack's; the
-- runtime may read, insert and update it, never delete (an item is discontinued instead).
-- Additive only: the new columns are nullable and nothing is removed, so the previous Worker keeps
-- working; what it writes after this runs has no vendor item, and the new Worker resolves such a
-- row by its vendor and master item. The backfill at the end fills the catalog from the aliases
-- and prices already kept. Generated by drizzle-kit from packs/materials/src/schema.ts; the index
-- on items without a SKU, the grants, row-level security and the backfill are hand-written.
