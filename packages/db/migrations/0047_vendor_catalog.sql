-- 4. Each vendor item's last price: its newest price by date (then the latest recorded), with the
-- record it came from (invariant 10). The history stays in price_observation.
UPDATE vendor_item v SET
  last_price = l.unit_price_std,
  last_price_std = l.unit_price_std,
  last_price_on = l.observed_on,
  last_price_source = CASE
    WHEN l.raw_record_id IS NOT NULL THEN 'qbo_bill'
    WHEN l.doc_line_id IS NOT NULL THEN 'invoice'
    ELSE 'import' END,
  last_price_source_id = coalesce(l.doc_line_id, l.raw_record_id),
  currency = l.currency
FROM (
  SELECT DISTINCT ON (vendor_item_id) vendor_item_id, unit_price_std, observed_on, currency,
    doc_line_id, raw_record_id
  FROM price_observation WHERE vendor_item_id IS NOT NULL
  ORDER BY vendor_item_id, observed_on DESC, created_at DESC, id DESC
) l
WHERE l.vendor_item_id = v.id;
