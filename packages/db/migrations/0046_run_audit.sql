-- The run audit (docs/plan.md §1.86 "Run audit (wave 6)"): `owner_check` is the owner's check on
-- each attempt at a v4 process's read, skill and write steps (clean, flagged, reviewed, not watched;
-- how the attempt ended; why a review that was due wasn't made, and why it was due), one row per
-- run, node and attempt; `run_audit` is a run queued for a person's audit when it finished (it
-- wrote to a client's tool, or the client's sampling rule picked it by a hash of its id) or by
-- hand; `run_audit_mark` is a reviewer's mark on a run (looks right, or a problem with a note). All
-- three are client tables with forced row-level security on tenant_id (invariant 1), insert only
-- (grants and trigger): a later mark supersedes an earlier one for display, every mark is kept.
-- Back office only (invariant 11). New tables only, so the previous Worker keeps working.
-- `owner_check.decision_id` references `oversight_decision(id)` alone: that table has no unique
-- (id, tenant_id) to reference (0029), and the store reads the decision within the run's own
-- client. Generated by drizzle-kit from packages/db/src/schema.ts; the grants, the triggers and
-- row-level security at the end are hand-written.
