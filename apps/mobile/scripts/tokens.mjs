#!/usr/bin/env node
// Writes src/theme/tokens.ts from the design system's tokens.json (the source of truth): colours in
// light and dark, spacing, radii and the text styles, in React Native's units (numbers, no px).
// Run `pnpm --filter @countersign/mobile tokens` after the owner's next design-system delivery.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../packages/design-system/tokens.json", import.meta.url);
const out = new URL("../src/theme/tokens.ts", import.meta.url);
const t = JSON.parse(readFileSync(root, "utf8"));

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (v) => (typeof v === "number" ? v : Number.parseFloat(String(v)));

function colours(theme) {
  const byName = new Map(t.color.tokens.map((c) => [c.name, c.value]));
  const resolve = (v) => {
    if (typeof v === "string") {
      const ref = /^\{(.+)\}$/.exec(v);
      return ref ? resolve(byName.get(ref[1])) : v;
    }
    return resolve(v[theme]);
  };
  return Object.fromEntries(t.color.tokens.map((c) => [camel(c.name), resolve(c.value)]));
}

const space = Object.fromEntries(
  t.spacing.tokens.map((s) => [s.name.replace(/^space-/, "").replace("-", "_"), px(s.value)]),
);
const radius = Object.fromEntries(
  t.radius.tokens.map((r) => [r.name.replace(/^radius-/, ""), px(r.value)]),
);

const type = {};
for (const group of t.type.groups) {
  for (const s of group.styles) {
    const size = px(s.fontSize);
    const line = typeof s.lineHeight === "number" ? s.lineHeight * size : px(s.lineHeight);
    const style = {
      family: s.family ?? group.family ?? "sans",
      fontSize: size,
      lineHeight: line,
      fontWeight: s.fontWeight,
    };
    if (s.letterSpacing) style.letterSpacing = Math.round(px(s.letterSpacing) * size * 100) / 100;
    if (s.name === "eyebrow") style.uppercase = true;
    type[s.name] = style;
  }
}

const body = `// Generated by scripts/tokens.mjs from packages/design-system/tokens.json. Do not edit by hand.

export const colors = {
  light: ${JSON.stringify(colours("light"), null, 2).replace(/\n/g, "\n  ")},
  dark: ${JSON.stringify(colours("dark"), null, 2).replace(/\n/g, "\n  ")},
} as const;

export type ColorName = keyof (typeof colors)["light"];

export const space = ${JSON.stringify(space, null, 2)} as const;

export const radius = ${JSON.stringify(radius, null, 2)} as const;

export const type = ${JSON.stringify(type, null, 2)} as const;

export type TypeName = keyof typeof type;
`;
writeFileSync(out, body);
console.log(`wrote ${out.pathname}`);
