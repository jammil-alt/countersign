/** One of the report's words in `locale`, with its `{placeholders}` filled. */
export function reportWord(
  locale: Locale,
  key: ReportKey,
  params: Record<string, string | number> = {},
): string {
  const text = REPORT_WORDS[locale]?.[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
