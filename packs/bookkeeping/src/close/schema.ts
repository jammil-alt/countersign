// The Close pack's tables (docs/plan.md §1.232, Wave Y item Y3; migration 0090): a month's close
// for one client and one accounting connection, its checklist, and the journal entries proposed for
// it (accruals, their reversals and recurring journals). The Close pack lives beside the
// Bookkeeping pack in this package (its own manifest, id `close`) because it reads the area's
// reconciliations and a pack never imports another pack. Same tenancy rules as every pack
// (CLAUDE.md invariant 1): tenant_id on every table, forced RLS on app.tenant_ids, composite
// (id, tenant_id) foreign keys, so a row points only at the same client's rows.
//
// Migration 0090 creates them (generated by drizzle-kit from this file, which the db package's
// drizzle config lists, plus hand-written SQL for the grants, history triggers, RLS and the pack
// comments). Imports only drizzle-orm and the platform's schema at runtime, so drizzle-kit loads it.

import {
  agentVersion,
  appUser,
  connection,
  externalAction,
  ledgerAccount,
  run,
  tenant,
} from "@countersign/db";
import { type SQL, sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  check,
  date,
  foreignKey,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  text,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

// ── Allowed values ───────────────────────────────────────────────────────────────────────────────

/** `open` until a person signs the period off; a signed-off period never changes. */
export const CLOSE_PERIOD_STATUSES = ["open", "signed_off"] as const;
export type ClosePeriodStatus = (typeof CLOSE_PERIOD_STATUSES)[number];

/** What a checklist line checks. */
export const CLOSE_ITEM_KINDS = [
  /** One bank or card account reconciled through the period's end. */
  "reconciliation",
  /** Transactions in the period on an uncategorized account (books health's check). */
  "uncategorized",
  /** Bills entered twice and vendors kept twice (books health's checks). */
  "duplicates",
  /** Bank transactions in the period not yet booked. */
  "unbooked",
  /** Every proposed journal entry of the period decided: posted or turned down. */
  "entries",
] as const;
export type CloseItemKind = (typeof CLOSE_ITEM_KINDS)[number];
/** `done` by the check itself; `waived` only by a person, with a note. */
export const CLOSE_ITEM_STATUSES = ["open", "done", "waived"] as const;
export type CloseItemStatus = (typeof CLOSE_ITEM_STATUSES)[number];

export const CLOSE_ENTRY_KINDS = ["accrual", "reversal", "recurring"] as const;
export type CloseEntryKind = (typeof CLOSE_ENTRY_KINDS)[number];
export const CLOSE_ENTRY_STATUSES = [
  "proposed",
  "rejected",
  "posted",
  "failed",
  "superseded",
] as const;
export type CloseEntryStatus = (typeof CLOSE_ENTRY_STATUSES)[number];
/** An entry that still stands: at most one per period and key. */
export const LIVE_CLOSE_ENTRY_STATUSES = ["proposed", "posted"] as const;
/**
 * Who proposed it: `pattern` (code, from the vendor's bills in earlier months), `repeat` (code, an
 * entry posted last period that repeats or reverses), `model` (an agent, with its sources) or
 * `person`.
 */
export const CLOSE_ENTRY_PROPOSERS = ["pattern", "repeat", "model", "person"] as const;
export type CloseEntryProposer = (typeof CLOSE_ENTRY_PROPOSERS)[number];
export const CLOSE_POSTINGS = ["debit", "credit"] as const;
export type ClosePosting = (typeof CLOSE_POSTINGS)[number];

function oneOf(column: AnyPgColumn, values: readonly string[]): SQL {
  return sql`${column} in (${sql.raw(values.map((v) => `'${v}'`).join(", "))})`;
}

const id = () => uuid("id").primaryKey().default(sql`uuid_generate_v7()`);
const tenantId = () =>
  uuid("tenant_id")
    .notNull()
    .references(() => tenant.id);
const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();
const updatedAt = () => timestamp("updated_at", { withTimezone: true }).notNull().defaultNow();
const ts = (name: string) => timestamp(name, { withTimezone: true });
const money = (name: string) => numeric(name, { precision: 14, scale: 4 });

// ── Tables ───────────────────────────────────────────────────────────────────────────────────────

/** One month's close of one accounting connection (one company's general ledger). */
export const closePeriod = pgTable(
  "close_period",
  {
    id: id(),
    tenantId: tenantId(),
    /** The accounting connection (QuickBooks) whose books close. */
    connectionId: uuid("connection_id").notNull(),
    periodStart: date("period_start").notNull(),
    periodEnd: date("period_end").notNull(),
    currency: text("currency").notNull().default("USD"),
    status: text("status").$type<ClosePeriodStatus>().notNull().default("open"),
    /** The agent version that last checked it (invariant 10). */
    agentVersionId: uuid("agent_version_id").references(() => agentVersion.id),
    runId: uuid("run_id"),
    checkedAt: ts("checked_at"),
    signedOffBy: uuid("signed_off_by").references(() => appUser.id),
    signedOffAt: ts("signed_off_at"),
    /** The person's words at sign-off. */
    note: text("note"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique("close_period_id_tenant_key").on(t.id, t.tenantId),
    // One close per company and month.
    unique("close_period_month_key").on(t.tenantId, t.connectionId, t.periodStart),
    foreignKey({
      name: "close_period_connection_fk",
      columns: [t.connectionId, t.tenantId],
      foreignColumns: [connection.id, connection.tenantId],
    }),
    foreignKey({
      name: "close_period_run_fk",
      columns: [t.runId, t.tenantId],
      foreignColumns: [run.id, run.tenantId],
    }),
    index("close_period_end_idx").on(t.tenantId, t.periodEnd),
    check("close_period_status_check", oneOf(t.status, CLOSE_PERIOD_STATUSES)),
    check("close_period_dates_check", sql`${t.periodEnd} >= ${t.periodStart}`),
    check(
      "close_period_signed_off_check",
      sql`(${t.status} = 'signed_off') = (${t.signedOffBy} is not null and ${t.signedOffAt} is not null)`,
    ),
    check("close_period_note_check", sql`${t.note} is null or length(${t.note}) <= 1000`),
  ],
);

/** One line of a period's checklist: what was checked, what is left, and the records behind it. */
export const closeItem = pgTable(
  "close_item",
  {
    id: id(),
    tenantId: tenantId(),
    periodId: uuid("period_id").notNull(),
    /** Stable across re-checks: `reconciliation:<ledger account id>`, `uncategorized`, … */
    key: text("key").notNull(),
    kind: text("kind").$type<CloseItemKind>().notNull(),
    title: text("title").notNull(),
    status: text("status").$type<CloseItemStatus>().notNull().default("open"),
    /** The dollars still open (0 when done). */
    amount: money("amount"),
    /** How many records are still open. */
    count: integer("count").notNull().default(0),
    /** One sentence: the result and its number. */
    summary: text("summary"),
    /** A few examples (decimal strings), as data. */
    detail: jsonb("detail").$type<Record<string, unknown>>().notNull().default({}),
    /** Record ids the line rests on (invariant 10). */
    sources: jsonb("sources").$type<string[]>().notNull().default([]),
    agentVersionId: uuid("agent_version_id").references(() => agentVersion.id),
    checkedAt: ts("checked_at"),
    /** The person who waived it. */
    waivedBy: uuid("waived_by").references(() => appUser.id),
    note: text("note"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique("close_item_id_tenant_key").on(t.id, t.tenantId),
    unique("close_item_key").on(t.tenantId, t.periodId, t.key),
    foreignKey({
      name: "close_item_period_fk",
      columns: [t.periodId, t.tenantId],
      foreignColumns: [closePeriod.id, closePeriod.tenantId],
    }),
    check("close_item_kind_check", oneOf(t.kind, CLOSE_ITEM_KINDS)),
    check("close_item_status_check", oneOf(t.status, CLOSE_ITEM_STATUSES)),
    check("close_item_count_check", sql`${t.count} >= 0`),
    // Only a person waives a line, and says why.
    check(
      "close_item_waived_check",
      sql`(${t.status} = 'waived') = (${t.waivedBy} is not null and ${t.note} is not null)`,
    ),
    check("close_item_note_check", sql`${t.note} is null or length(${t.note}) <= 500`),
  ],
);

/**
 * A journal entry proposed for a period: an accrual, the reversal of last period's, or a recurring
 * journal. Written to the accounting tool only through the connector's external tool, once, after
 * approval (invariant 8); here only its status columns change after it is proposed.
 */
export const closeEntry = pgTable(
  "close_entry",
  {
    id: id(),
    tenantId: tenantId(),
    periodId: uuid("period_id").notNull(),
    kind: text("kind").$type<CloseEntryKind>().notNull(),
    /** What it is, stable across re-checks (`accrual:<vendor>:<account>`, `repeat:<entry id>`). */
    entryKey: text("entry_key").notNull(),
    status: text("status").$type<CloseEntryStatus>().notNull().default("proposed"),
    proposedBy: text("proposed_by").$type<CloseEntryProposer>().notNull(),
    txnDate: date("txn_date").notNull(),
    /** An accrual reverses on this day (the next period's first). */
    reverseOn: date("reverse_on"),
    /** The total of its debits, which equals the total of its credits. */
    amount: money("amount").notNull(),
    currency: text("currency").notNull().default("USD"),
    memo: text("memo").notNull(),
    /** Why, in a sentence, with the numbers. */
    reason: text("reason"),
    /** The posted entry it repeats or reverses. */
    fromEntryId: uuid("from_entry_id"),
    sources: jsonb("sources").$type<string[]>().notNull().default([]),
    agentVersionId: uuid("agent_version_id").references(() => agentVersion.id),
    runId: uuid("run_id"),
    /** The person who proposed it, or who turned it down. */
    userId: uuid("user_id").references(() => appUser.id),
    externalActionId: uuid("external_action_id"),
    /** The journal entry's id in the accounting tool, once written. */
    qboId: text("qbo_id"),
    error: text("error"),
    createdAt: createdAt(),
    decidedAt: ts("decided_at"),
    postedAt: ts("posted_at"),
  },
  (t) => [
    unique("close_entry_id_tenant_key").on(t.id, t.tenantId),
    foreignKey({
      name: "close_entry_period_fk",
      columns: [t.periodId, t.tenantId],
      foreignColumns: [closePeriod.id, closePeriod.tenantId],
    }),
    foreignKey({
      name: "close_entry_from_fk",
      columns: [t.fromEntryId, t.tenantId],
      foreignColumns: [t.id, t.tenantId],
    }),
    foreignKey({
      name: "close_entry_run_fk",
      columns: [t.runId, t.tenantId],
      foreignColumns: [run.id, run.tenantId],
    }),
    foreignKey({
      name: "close_entry_external_action_fk",
      columns: [t.externalActionId, t.tenantId],
      foreignColumns: [externalAction.id, externalAction.tenantId],
    }),
    // One live entry per period and key: a re-check never proposes the same entry twice.
    uniqueIndex("close_entry_live_key")
      .on(t.tenantId, t.periodId, t.entryKey)
      .where(sql`${t.status} in ('proposed', 'posted')`),
    index("close_entry_period_idx").on(t.tenantId, t.periodId, t.status),
    check("close_entry_kind_check", oneOf(t.kind, CLOSE_ENTRY_KINDS)),
    check("close_entry_status_check", oneOf(t.status, CLOSE_ENTRY_STATUSES)),
    check("close_entry_proposed_by_check", oneOf(t.proposedBy, CLOSE_ENTRY_PROPOSERS)),
    check("close_entry_amount_check", sql`${t.amount} > 0`),
    check("close_entry_memo_check", sql`length(${t.memo}) between 1 and 400`),
    check("close_entry_posted_check", sql`${t.status} <> 'posted' or ${t.qboId} is not null`),
    check(
      "close_entry_reversal_check",
      sql`${t.kind} <> 'reversal' or ${t.fromEntryId} is not null`,
    ),
    // Invariant 10: code's and a model's proposals name the agent version; a person's, the person.
    check(
      "close_entry_proposer_check",
      sql`${t.proposedBy} = 'person' and ${t.userId} is not null or ${t.proposedBy} <> 'person' and ${t.agentVersionId} is not null`,
    ),
    // Invariant 10: a model's proposal carries its sources.
    check(
      "close_entry_sources_check",
      sql`${t.proposedBy} <> 'model' or jsonb_array_length(${t.sources}) > 0`,
    ),
  ],
);

/** An entry's lines: debits and credits to the client's accounts, adding up (decimal.js). */
export const closeEntryLine = pgTable(
  "close_entry_line",
  {
    id: id(),
    tenantId: tenantId(),
    entryId: uuid("entry_id").notNull(),
    lineNo: integer("line_no").notNull(),
    ledgerAccountId: uuid("ledger_account_id").notNull(),
    posting: text("posting").$type<ClosePosting>().notNull(),
    amount: money("amount").notNull(),
    description: text("description"),
  },
  (t) => [
    unique("close_entry_line_no_key").on(t.entryId, t.lineNo),
    foreignKey({
      name: "close_entry_line_entry_fk",
      columns: [t.entryId, t.tenantId],
      foreignColumns: [closeEntry.id, closeEntry.tenantId],
    }),
    foreignKey({
      name: "close_entry_line_ledger_account_fk",
      columns: [t.ledgerAccountId, t.tenantId],
      foreignColumns: [ledgerAccount.id, ledgerAccount.tenantId],
    }),
    index("close_entry_line_entry_idx").on(t.tenantId, t.entryId),
    check("close_entry_line_posting_check", oneOf(t.posting, CLOSE_POSTINGS)),
    check("close_entry_line_amount_check", sql`${t.amount} > 0`),
  ],
);

