// The AP pack's tables (Plan entry §1.233, Wave Y item Y4): bills to pay, each line's account, and
// goods received against a purchase order. The AP pack lives beside the Materials pack in this
// package (its own manifest, id `ap`, `extends: "materials"`) because it reads the Purchasing
// area's purchase orders and a pack never imports another pack. Same tenancy rules as every pack
// (CLAUDE.md invariant 1): tenant_id on every table, forced RLS on app.tenant_ids, composite
// (id, tenant_id) foreign keys, so a row points only at the same client's rows.
//
// No payment (owner, Wave Y): a bill ends approved on a week's approve-to-pay list. Nothing here
// pays, schedules a payment or writes to a client's tool.
//
// The migration that creates them is generated by drizzle-kit from this file (the db package's
// drizzle config lists it), plus hand-written SQL for the grants, the history trigger, RLS and the
// pack comments. Imports only drizzle-orm and schemas at runtime, so drizzle-kit loads it.

import {
  agentVersion,
  appUser,
  docExtraction,
  docLine,
  document,
  ledgerAccount,
  run,
  tenant,
  transaction,
  vendor,
} from "@countersign/db";
import { type SQL, sql } from "drizzle-orm";
import {
  type AnyPgColumn,
  check,
  date,
  foreignKey,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from "drizzle-orm/pg-core";
import { purchaseRequest, purchaseRequestLine } from "../schema";

// ── Allowed values ───────────────────────────────────────────────────────────────────────────────

/**
 * A bill's decision: `open` until a person decides it on the week's list; `approved` to pay,
 * `held` (asked about, back on next week's list) or `rejected` (not to pay). Approved and rejected
 * are final.
 */
// DECISION: approved and rejected never change (a bill approved by mistake is a person's call in
// their accounting tool, where nothing here pays it); held goes back to open-for-decision on the
// next list.
export const AP_BILL_STATUSES = ["open", "approved", "held", "rejected"] as const;
export type ApBillStatus = (typeof AP_BILL_STATUSES)[number];

/** How a bill stands against its purchase order (the matching engine's `bill_to_po`). */
export const AP_MATCH_STATUSES = [
  /** Not matched yet. */
  "pending",
  /** One order, by its reference and amount (or within the configuration's tolerance). */
  "matched",
  /** One order by reference, the amounts differing: part of it, or more than it. */
  "partial",
  /** An order the fuzzy tier or the model thought likely: a person confirms on the list. */
  "proposed",
  /** No order fits (a bill without a purchase order). */
  "none",
] as const;
export type ApMatchStatus = (typeof AP_MATCH_STATUSES)[number];

/**
 * Who coded a line: `history` (code: the account this vendor's bills were coded to before) or
 * `person`. A model's suggestion is only ever `proposed_*` until a person takes it (invariant 7).
 */
export const AP_CODED_BY = ["history", "person"] as const;
export type ApCodedBy = (typeof AP_CODED_BY)[number];

function oneOf(column: AnyPgColumn, values: readonly string[]): SQL {
  return sql`${column} in (${sql.raw(values.map((v) => `'${v}'`).join(", "))})`;
}

const id = () => uuid("id").primaryKey().default(sql`uuid_generate_v7()`);
const tenantId = () =>
  uuid("tenant_id")
    .notNull()
    .references(() => tenant.id);
const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();
const updatedAt = () => timestamp("updated_at", { withTimezone: true }).notNull().defaultNow();
const ts = (name: string) => timestamp(name, { withTimezone: true });
const money = (name: string) => numeric(name, { precision: 14, scale: 4 });

// ── Tables ───────────────────────────────────────────────────────────────────────────────────────

/** One bill to pay: a vendor invoice's purchase, as AP prepared it, and its decision. */
export const apBill = pgTable(
  "ap_bill",
  {
    id: id(),
    tenantId: tenantId(),
    /** The purchase (`transaction`, kind bill) the invoice made or was linked to. */
    transactionId: uuid("transaction_id").notNull(),
    /** The invoice the bill came in as (email or upload), when there is one. */
    documentId: uuid("document_id"),
    /** The reading the bill was prepared from (immutable: a new reading is prepared again). */
    extractionId: uuid("extraction_id"),
    vendorId: uuid("vendor_id"),
    invoiceNumber: text("invoice_number"),
    invoiceDate: date("invoice_date"),
    dueDate: date("due_date"),
    amount: money("amount").notNull(),
    currency: text("currency").notNull().default("USD"),
    status: text("status").$type<ApBillStatus>().notNull().default("open"),
    matchStatus: text("match_status").$type<ApMatchStatus>().notNull().default("pending"),
    /** The purchase order (an ordered purchase request) it matched. */
    purchaseRequestId: uuid("purchase_request_id"),
    /** The match as the engine gave it: tier, rule, score, difference, reference, receipts. */
    match: jsonb("match").$type<Record<string, unknown>>().notNull().default({}),
    /** The flags on it: duplicate, price variance, quantity, no order, uncoded (`ApFlag[]`). */
    flags: jsonb("flags").$type<unknown[]>().notNull().default([]),
    /** Monday of the week whose approve-to-pay list it is on; null until listed. */
    payWeek: date("pay_week"),
    decidedBy: uuid("decided_by").references(() => appUser.id),
    decidedAt: ts("decided_at"),
    /** The person's words with the decision. */
    decisionNote: text("decision_note"),
    /** The agent version that last prepared it (invariant 10). */
    agentVersionId: uuid("agent_version_id").references(() => agentVersion.id),
    runId: uuid("run_id"),
    /** The records it rests on: the document, its reading, the purchase, the order. */
    sources: jsonb("sources").$type<string[]>().notNull().default([]),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique("ap_bill_id_tenant_key").on(t.id, t.tenantId),
    // One bill per purchase.
    unique("ap_bill_transaction_key").on(t.tenantId, t.transactionId),
    foreignKey({
      name: "ap_bill_transaction_fk",
      columns: [t.transactionId, t.tenantId],
      foreignColumns: [transaction.id, transaction.tenantId],
    }),
    foreignKey({
      name: "ap_bill_document_fk",
      columns: [t.documentId, t.tenantId],
      foreignColumns: [document.id, document.tenantId],
    }),
    foreignKey({
      name: "ap_bill_extraction_fk",
      columns: [t.extractionId, t.tenantId],
      foreignColumns: [docExtraction.id, docExtraction.tenantId],
    }),
    foreignKey({
      name: "ap_bill_vendor_fk",
      columns: [t.vendorId, t.tenantId],
      foreignColumns: [vendor.id, vendor.tenantId],
    }),
    foreignKey({
      name: "ap_bill_purchase_request_fk",
      columns: [t.purchaseRequestId, t.tenantId],
      foreignColumns: [purchaseRequest.id, purchaseRequest.tenantId],
    }),
    foreignKey({
      name: "ap_bill_run_fk",
      columns: [t.runId, t.tenantId],
      foreignColumns: [run.id, run.tenantId],
    }),
    index("ap_bill_week_idx").on(t.tenantId, t.payWeek, t.status),
    index("ap_bill_vendor_idx").on(t.tenantId, t.vendorId, t.invoiceDate),
    check("ap_bill_status_check", oneOf(t.status, AP_BILL_STATUSES)),
    check("ap_bill_match_status_check", oneOf(t.matchStatus, AP_MATCH_STATUSES)),
    check("ap_bill_currency_check", sql`${t.currency} ~ '^[A-Z]{3}$'`),
    // A decided bill names who decided it and when; an open one names neither.
    check(
      "ap_bill_decided_check",
      sql`(${t.status} = 'open') = (${t.decidedBy} is null) and (${t.decidedBy} is null) = (${t.decidedAt} is null)`,
    ),
    // A decision is made on a week's list.
    check("ap_bill_listed_check", sql`${t.status} = 'open' or ${t.payWeek} is not null`),
    check(
      "ap_bill_pay_week_check",
      sql`${t.payWeek} is null or extract(isodow from ${t.payWeek}) = 1`,
    ),
    check(
      "ap_bill_order_check",
      sql`(${t.purchaseRequestId} is not null) = (${t.matchStatus} in ('matched', 'partial', 'proposed'))`,
    ),
    check("ap_bill_flags_check", sql`jsonb_typeof(${t.flags}) = 'array'`),
    check("ap_bill_sources_check", sql`jsonb_typeof(${t.sources}) = 'array'`),
    check(
      "ap_bill_note_check",
      sql`${t.decisionNote} is null or length(${t.decisionNote}) <= 1000`,
    ),
  ],
);

/** One line of a bill and the account it is coded to. */
export const apBillLine = pgTable(
  "ap_bill_line",
  {
    id: id(),
    tenantId: tenantId(),
    apBillId: uuid("ap_bill_id").notNull(),
    lineNo: integer("line_no").notNull(),
    /** The invoice line as read (its words stay there: data, never instructions). */
    docLineId: uuid("doc_line_id"),
    amount: money("amount").notNull(),
    ledgerAccountId: uuid("ledger_account_id"),
    codedBy: text("coded_by").$type<ApCodedBy>(),
    /** Who coded it, when a person did. */
    codedByUserId: uuid("coded_by_user_id").references(() => appUser.id),
    /** A model's suggestion, for a person to take or not; never the line's account by itself. */
    proposedLedgerAccountId: uuid("proposed_ledger_account_id"),
    proposalReason: text("proposal_reason"),
    proposalAgentVersionId: uuid("proposal_agent_version_id").references(() => agentVersion.id),
    /** The order line it matched, when the bill matched an order. */
    purchaseRequestLineId: uuid("purchase_request_line_id"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique("ap_bill_line_id_tenant_key").on(t.id, t.tenantId),
    unique("ap_bill_line_no_key").on(t.apBillId, t.lineNo),
    foreignKey({
      name: "ap_bill_line_bill_fk",
      columns: [t.apBillId, t.tenantId],
      foreignColumns: [apBill.id, apBill.tenantId],
    }),
    foreignKey({
      name: "ap_bill_line_doc_line_fk",
      columns: [t.docLineId, t.tenantId],
      foreignColumns: [docLine.id, docLine.tenantId],
    }),
    foreignKey({
      name: "ap_bill_line_account_fk",
      columns: [t.ledgerAccountId, t.tenantId],
      foreignColumns: [ledgerAccount.id, ledgerAccount.tenantId],
    }),
    foreignKey({
      name: "ap_bill_line_proposed_account_fk",
      columns: [t.proposedLedgerAccountId, t.tenantId],
      foreignColumns: [ledgerAccount.id, ledgerAccount.tenantId],
    }),
    foreignKey({
      name: "ap_bill_line_request_line_fk",
      columns: [t.purchaseRequestLineId, t.tenantId],
      foreignColumns: [purchaseRequestLine.id, purchaseRequestLine.tenantId],
    }),
    index("ap_bill_line_account_idx").on(t.tenantId, t.ledgerAccountId),
    check("ap_bill_line_no_check", sql`${t.lineNo} >= 1`),
    check(
      "ap_bill_line_coded_by_check",
      sql`${t.codedBy} is null or ${oneOf(t.codedBy, AP_CODED_BY)}`,
    ),
    check(
      "ap_bill_line_coded_check",
      sql`(${t.ledgerAccountId} is null) = (${t.codedBy} is null) and (${t.codedByUserId} is not null) = (coalesce(${t.codedBy}, '') = 'person')`,
    ),
    check(
      "ap_bill_line_proposal_check",
      sql`(${t.proposedLedgerAccountId} is null) = (${t.proposalAgentVersionId} is null) and (${t.proposalReason} is null or length(${t.proposalReason}) <= 500)`,
    ),
  ],
);

/**
 * Goods received against a purchase order: one line of it, or the whole order. A log, never
 * changed: a correction is a new row (a negative quantity takes some back).
 */
export const apReceipt = pgTable(
  "ap_receipt",
  {
    id: id(),
    tenantId: tenantId(),
    purchaseRequestId: uuid("purchase_request_id").notNull(),
    /** Null: the whole order arrived as ordered. */
    purchaseRequestLineId: uuid("purchase_request_line_id"),
    /** How many arrived, in the order line's unit; null for the whole order. */
    qty: numeric("qty", { precision: 14, scale: 4 }),
    receivedOn: date("received_on").notNull(),
    /** A delivery ticket or packing slip, when one came in. */
    documentId: uuid("document_id"),
    note: text("note"),
    recordedByUserId: uuid("recorded_by_user_id").references(() => appUser.id),
    agentVersionId: uuid("agent_version_id").references(() => agentVersion.id),
    runId: uuid("run_id"),
    sources: jsonb("sources").$type<string[]>().notNull().default([]),
    createdAt: createdAt(),
  },
  (t) => [
    unique("ap_receipt_id_tenant_key").on(t.id, t.tenantId),
    foreignKey({
      name: "ap_receipt_request_fk",
      columns: [t.purchaseRequestId, t.tenantId],
      foreignColumns: [purchaseRequest.id, purchaseRequest.tenantId],
    }),
    foreignKey({
      name: "ap_receipt_request_line_fk",
      columns: [t.purchaseRequestLineId, t.tenantId],
      foreignColumns: [purchaseRequestLine.id, purchaseRequestLine.tenantId],
    }),
    foreignKey({
      name: "ap_receipt_document_fk",
      columns: [t.documentId, t.tenantId],
      foreignColumns: [document.id, document.tenantId],
    }),
    foreignKey({
      name: "ap_receipt_run_fk",
      columns: [t.runId, t.tenantId],
      foreignColumns: [run.id, run.tenantId],
    }),
    index("ap_receipt_request_idx").on(t.tenantId, t.purchaseRequestId),
    // A line's receipt says how many; the whole order's says none.
    check(
      "ap_receipt_qty_check",
      sql`(${t.purchaseRequestLineId} is null) = (${t.qty} is null) and (${t.qty} is null or ${t.qty} <> 0)`,
    ),
    check(
      "ap_receipt_recorded_by_check",
      sql`num_nonnulls(${t.recordedByUserId}, ${t.agentVersionId}) = 1`,
    ),
    check("ap_receipt_note_check", sql`${t.note} is null or length(${t.note}) <= 500`),
    check("ap_receipt_sources_check", sql`jsonb_typeof(${t.sources}) = 'array'`),
  ],
);

/** The pack's tenant tables, in the order its RLS tests walk them. */
export const AP_TABLES = [apBill, apBillLine, apReceipt] as const;
